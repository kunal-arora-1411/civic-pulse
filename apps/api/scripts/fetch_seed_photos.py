"""Fetch the demo seed's photos from the evaluation manifest.

The seed used to draw a flat colour with "SYNTHETIC" on it, which made every
report card in the product look identical and made the screenshots useless as
a demonstration. This downloads real street photos instead, from the same
openly licensed set the Phase 2 evaluation already vetted: every candidate is
recorded in `scripts/eval/manifest.csv` with its source page, author, licence
and the sha256 of the bytes, and this script re-verifies that hash before
writing a file.

    cd apps/api
    uv run python scripts/fetch_seed_photos.py

Outputs (both committed, so the seed needs no network):

    scripts/seed_photos/<category>/<sha256 prefix>.jpg
    scripts/seed_photos/ATTRIBUTION.md

Licence policy: CC0 and public domain are preferred, then CC BY. Share-alike
(CC BY-SA) is acceptable for a demo but its attribution is written the same
way. Re-running is a no-op unless a file is missing or the manifest changed.
"""

from __future__ import annotations

import argparse
import collections
import csv
import hashlib
import io
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).parent
MANIFEST = ROOT / "eval" / "manifest.csv"
OUT = ROOT / "seed_photos"

# Labels in the manifest map onto the seed's category codes.
LABELS = ("pothole", "waste", "waterlogging", "streetlight", "drainage")
PER_CATEGORY = 6
# Matches the size the seed used to generate, so downstream code and the
# cards' aspect ratio are unchanged.
SIZE = (1200, 900)

USER_AGENT = (
    "CivicPulse-seed-photos/0.1 (open-source civic issue reporting; "
    "seeded demo data from openly licensed photos)"
)

# Permissive first: a demo should not carry obligations it does not need.
LICENCE_RANK = {"CC0": 0, "Public domain": 0, "CC BY 2.0": 1, "CC BY 3.0": 1, "CC BY 4.0": 1}


def rank(licence: str) -> int:
    return LICENCE_RANK.get(licence, 2)


def candidates(rows: list[dict[str, str]], label: str) -> list[dict[str, str]]:
    """Every usable candidate for one label, best licence first.

    Sorted by licence rank then by hash, so the choice is stable when the
    manifest is regenerated with the same images.
    """
    usable = [
        row
        for row in rows
        if row["label"] == label
        and row["license"] not in {"", "unknown"}
        and row["path_or_url"]
    ]
    usable.sort(key=lambda row: (rank(row["license"]), row["sha256"]))
    return usable


def fetch(url: str, expected_sha: str) -> bytes:
    # URLs come from the committed sources.json manifest and every download is
    # sha256-checked below, so the file:// concern behind S310 does not apply.
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})  # noqa: S310
    with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310
        data = response.read()
    actual = hashlib.sha256(data).hexdigest()
    if expected_sha and actual != expected_sha:
        raise ValueError(f"sha256 changed upstream: {url}")
    return data


def to_card_jpeg(data: bytes) -> bytes:
    """Exactly SIZE, centre crop, so every card has the same shape."""
    with Image.open(io.BytesIO(data)) as image:
        image = ImageOps.exif_transpose(image).convert("RGB")
        fitted = ImageOps.fit(image, SIZE, method=Image.Resampling.LANCZOS)
        buffer = io.BytesIO()
        fitted.save(buffer, "JPEG", quality=82, optimize=True)
        return buffer.getvalue()


def attribution_markdown(kept: list[tuple[dict[str, str], str]]) -> str:
    lines = [
        "# Demo seed photo credits",
        "",
        "These photos are the demo data's report pictures. They are **not**",
        "synthetic: they are real photographs, published under the licence named",
        "against each one, and were downloaded from the URL given with it.",
        "",
        "Generated by `scripts/fetch_seed_photos.py` from",
        "[`scripts/eval/manifest.csv`](../eval/manifest.csv), the openly licensed",
        "set used for the Phase 2 evaluation. Do not add a file here without its",
        "row here.",
        "",
        "| File | Category | Author | Licence | Source |",
        "|---|---|---|---|---|",
    ]
    for row, path in sorted(kept, key=lambda item: (item[0]["label"], item[1])):
        author = (row["attribution"] or "unknown").replace("|", "/").strip()
        source = row["source"] or row["path_or_url"]
        licence = row["license"]
        if row["license_url"]:
            licence = f"[{licence}]({row['license_url']})"
        lines.append(
            f"| `{path}` | {row['label']} | {author} | {licence} | [source]({source}) |"
        )
    lines += [
        "",
        "Re-run `uv run python scripts/fetch_seed_photos.py` to restore any file",
        "from the manifest; each download is checked against the recorded sha256.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="rewrite files that exist")
    args = parser.parse_args()

    if not MANIFEST.exists():
        print(f"missing manifest: {MANIFEST}", file=sys.stderr)
        return 1
    rows = list(csv.DictReader(MANIFEST.open()))

    kept: list[tuple[dict[str, str], str]] = []
    problems: list[str] = []
    for label in LABELS:
        taken = 0
        # Walk the whole candidate list rather than the first N: an image
        # whose bytes changed upstream fails its sha256 check, and the
        # category should still end up with a full set.
        for row in candidates(rows, label):
            if taken >= PER_CATEGORY:
                break
            sha = row["sha256"]
            relative = f"{label}/{sha[:16]}.jpg"
            target = OUT / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            if not (target.exists() and not args.force):
                try:
                    target.write_bytes(to_card_jpeg(fetch(row["path_or_url"], sha)))
                except (urllib.error.URLError, ValueError, OSError) as exc:
                    problems.append(f"{label} {sha[:8]}: {exc}")
                    continue
                print(f"  {relative}  {row['license']}  {row['attribution'][:40]}")
            kept.append((row, relative))
            taken += 1
        if taken < PER_CATEGORY:
            problems.append(f"{label}: only {taken} of {PER_CATEGORY} photos")

    (OUT / "ATTRIBUTION.md").write_text(attribution_markdown(kept))
    (OUT / "sources.json").write_text(
        json.dumps(
            [
                {
                    "file": relative,
                    "label": row["label"],
                    "source": row["source"],
                    "license": row["license"],
                    "license_url": row["license_url"],
                    "attribution": row["attribution"],
                    "sha256": row["sha256"],
                }
                for row, relative in kept
            ],
            indent=2,
        )
        + "\n"
    )
    counts = collections.Counter(row["label"] for row, _ in kept)
    print(f"wrote {len(kept)} photos to {OUT}: {dict(sorted(counts.items()))}")
    for problem in problems:
        print(f"  skipped {problem}", file=sys.stderr)
    # Skipped candidates are reported but not fatal: the set is complete.
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
